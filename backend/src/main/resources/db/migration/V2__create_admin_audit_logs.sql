CREATE TABLE admin_audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    actor_user_id bigint NOT NULL REFERENCES users(id),
    target_type varchar(30) NOT NULL,
    target_id bigint NOT NULL,
    action varchar(50) NOT NULL,
    before_value varchar(255) NOT NULL,
    after_value varchar(255) NOT NULL,
    CONSTRAINT admin_audit_logs_target_type_check CHECK (target_type IN ('USER')),
    CONSTRAINT admin_audit_logs_action_check CHECK (action IN ('USER_ROLE_CHANGED'))
);

CREATE INDEX idx_admin_audit_logs_created_at ON admin_audit_logs (created_at DESC);
CREATE INDEX idx_admin_audit_logs_actor_user_id ON admin_audit_logs (actor_user_id);
CREATE INDEX idx_admin_audit_logs_target ON admin_audit_logs (target_type, target_id);
